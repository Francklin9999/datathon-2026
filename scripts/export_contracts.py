#!/usr/bin/env python3
"""Generate catalog mirrors and a JSON Schema registry. No network access."""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

CATALOG_SECTIONS = {
    "MetricCode": 1,
    "MethodId": 2,
    "RuleId": 3,
    "NeeReason": 4,
    "LimitationCode": 5,
    "AuditCheckCode": 6,
    "ErrorCode": 7,
    "ThemeTag": 8,
    "AssetFlag": 9,
    "DatasetId": 10,
    "FeatureFlag": 11,
}


def catalog_values():
    text = (ROOT / "contracts/catalog.md").read_text(encoding="utf-8")
    sections = dict(re.findall(r"## (\d+)\.[^\n]*\n(.*?)(?=\n## |\Z)", text, re.S))
    values = {}
    for name, number in CATALOG_SECTIONS.items():
        section = sections[str(number)]
        if number in (8, 9):
            code_line = re.search(r"^`[^\n]+$", section, re.M).group()
            codes = re.findall(r"`([a-z_]+)`", code_line)
        else:
            codes = re.findall(r"^\| `([^`]+)`", section, re.M)
        values[name] = [code for code in codes if "<" not in code]
        if not values[name] or len(set(values[name])) != len(values[name]):
            raise ValueError(f"Empty or duplicate {name} catalog")
    return values


def enum_key(code):
    return re.sub(r"[^A-Za-z0-9]+", "_", code).upper()


def outputs(values):
    py = [
        "# Generated by scripts/export_contracts.py; do not edit.",
        "from enum import StrEnum",
        "",
        "",
    ]
    ts = ["// Generated by scripts/export_contracts.py; do not edit.", ""]
    for name, codes in values.items():
        py += [f"class {name}(StrEnum):"]
        py += [f"    {enum_key(code)} = {json.dumps(code)}" for code in codes]
        py += ["", ""]
        ts += [
            f"export const {name} = "
            + json.dumps({enum_key(c): c for c in codes}, indent=2)
            + " as const;",
            "",
        ]
    text = (ROOT / "contracts/catalog.md").read_text(encoding="utf-8")
    errors = dict(re.findall(r"^\| `([a-z_]+)` \| (\d{3}) \|", text, re.M))
    defaults = dict(
        (code, value == "true")
        for code, value in re.findall(r"^\| `([a-z_]+)` \| (true|false)[^|]*\|", text, re.M)
    )
    groups = {
        "equity": "equity",
        "etf_equity": "equity",
        "etf_bond": "fixed_income",
        "etf_commodity": "commodity",
        "crypto": "crypto",
        "cash": "cash",
    }
    py += ["ERROR_HTTP_STATUS = {"]
    py += [f"    ErrorCode.{enum_key(c)}: {v}," for c, v in errors.items()]
    py += ["}", "", "FEATURE_DEFAULTS = {"]
    py += [f"    FeatureFlag.{enum_key(c)}: {v}," for c, v in defaults.items()]
    py += ["}", "", "ASSET_GROUP_BY_CLASS = " + repr(groups), ""]
    ts += [
        "export const ERROR_HTTP_STATUS = "
        + json.dumps({c: int(v) for c, v in errors.items()}, indent=2)
        + " as const;",
        "export const FEATURE_DEFAULTS = " + json.dumps(defaults, indent=2) + " as const;",
        "export const ASSET_GROUP_BY_CLASS = " + json.dumps(groups, indent=2) + " as const;",
        "",
    ]
    return {
        ROOT / "backend/aplomb/contracts/catalog.py": "\n".join(py),
        ROOT / "web/src/contracts/catalog.ts": "\n".join(ts),
    }


def write_or_check(path, content, check):
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(
                f"Generated file is stale: {path.relative_to(ROOT)}; run npm run generate:contracts"
            )
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs(catalog_values()).items():
        write_or_check(path, content, args.check)
    from aplomb.contracts.registry import export_schema

    schema = export_schema()
    schema["x-spec-sha256"] = {
        # Line endings normalized: a Windows checkout (CRLF) hashes the same as CI (LF).
        name: hashlib.sha256((ROOT / "contracts" / name).read_bytes().replace(b"\r\n", b"\n")).hexdigest()
        for name in ("schemas.md", "catalog.md", "api.md", "run-events.md", "tools.md")
    }
    write_or_check(
        ROOT / "contracts/generated/schema.json",
        json.dumps(schema, indent=2, ensure_ascii=False) + "\n",
        args.check,
    )
    print("Contract catalog and JSON Schema are current.")


if __name__ == "__main__":
    main()
